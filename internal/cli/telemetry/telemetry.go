package telemetry

import (
	"bytes"
	"context"
	"encoding/json"
	"net/http"
	"os"
	"runtime"
	"strings"
	"time"

	cliconfig "gitlab.knoffice.tech/engineering/anycap/internal/cli/config"
	"gitlab.knoffice.tech/engineering/anycap/pkg/buildinfo"
)

const telemetryPath = "/v1/telemetry"

// sensitiveFlags lists flag names whose values must be redacted before
// telemetry upload. Matched case-insensitively against both --flag=val
// and --flag val forms.
var sensitiveFlags = map[string]bool{
	"password":   true,
	"token":      true,
	"secret":     true,
	"key":        true,
	"api-key":    true,
	"api_key":    true,
	"apikey":     true,
	"credential": true,
}

// redactArgs replaces values of sensitive flags with "[REDACTED]".
// It handles both --flag value and --flag=value forms.
func redactArgs(args []string) []string {
	out := make([]string, len(args))
	skipNext := false
	for i, arg := range args {
		if skipNext {
			out[i] = "[REDACTED]"
			skipNext = false
			continue
		}

		// --flag=value form
		if eqIdx := strings.Index(arg, "="); eqIdx > 0 && strings.HasPrefix(arg, "-") {
			name := strings.TrimLeft(arg[:eqIdx], "-")
			if sensitiveFlags[strings.ToLower(name)] {
				out[i] = arg[:eqIdx+1] + "[REDACTED]"
				continue
			}
		}

		// --flag value form: mark next arg for redaction
		if strings.HasPrefix(arg, "-") {
			name := strings.TrimLeft(arg, "-")
			if sensitiveFlags[strings.ToLower(name)] {
				out[i] = arg
				skipNext = true
				continue
			}
		}

		out[i] = arg
	}
	return out
}

// Event represents a single CLI telemetry event.
type Event struct {
	// Type is the event kind. Currently always "error".
	Type string `json:"type"`

	// DeviceID is the user external ID (u_xxx) or a random device UUID.
	DeviceID string `json:"device_id"`

	// Command is the subcommand path (e.g. "image generate").
	Command string `json:"command"`

	// Args is the full argument list (os.Args[1:]).
	Args []string `json:"args"`

	// DurationMs is the command execution time in milliseconds.
	DurationMs int64 `json:"duration_ms"`

	// Version is the CLI build version.
	Version string `json:"version"`

	// OS and Arch identify the platform.
	OS   string `json:"os"`
	Arch string `json:"arch"`

	// CI is true when a CI environment is detected.
	CI bool `json:"ci"`

	// TraceID is the per-invocation trace ID generated by the CLI.
	TraceID string `json:"trace_id,omitempty"`

	// Error is the error message.
	Error string `json:"error,omitempty"`

	// ErrorCode is the classified error code (e.g. "credit_insufficient").
	ErrorCode string `json:"error_code,omitempty"`

	// RequestID is the server-assigned request ID (from API errors).
	RequestID string `json:"request_id,omitempty"`

	// Timestamp is the Unix epoch second when the event was created.
	Timestamp int64 `json:"timestamp"`
}

// ErrorReport contains all the context needed to report a CLI error.
type ErrorReport struct {
	Command    string
	Args       []string
	Err        error
	ErrorCode  string
	RequestID  string
	TraceID    string
	DurationMs int64

	// Endpoint is the --endpoint flag value (may be empty). Used together
	// with ResolveEndpoint so telemetry is sent to the same server the
	// command targeted, respecting flag > env > config > default.
	Endpoint string
}

// ReportError sends an error telemetry event in the background (non-blocking).
// Silently does nothing if telemetry is disabled, not configured, or the
// endpoint is unreachable.
// Returns true if a telemetry event was dispatched (caller may want to sleep
// briefly to allow the goroutine to fire before os.Exit).
func ReportError(r ErrorReport) bool {
	if r.Err == nil {
		return false
	}

	// Check if telemetry is enabled.
	cfg, _ := cliconfig.Load()
	if !cfg.IsTelemetryEnabled() {
		return false
	}

	endpoint := cliconfig.ResolveEndpoint(r.Endpoint)
	if endpoint == "" {
		return false
	}

	event := Event{
		Type:       "error",
		DeviceID:   cliconfig.LoadOrCreateDeviceID(),
		Command:    r.Command,
		Args:       redactArgs(r.Args),
		DurationMs: r.DurationMs,
		Version:    buildinfo.Version,
		OS:         runtime.GOOS,
		Arch:       runtime.GOARCH,
		CI:         os.Getenv("CI") != "",
		TraceID:    r.TraceID,
		Error:      r.Err.Error(),
		ErrorCode:  r.ErrorCode,
		RequestID:  r.RequestID,
		Timestamp:  time.Now().Unix(),
	}

	// Fire and forget in background goroutine.
	go func() {
		body, err := json.Marshal(event)
		if err != nil {
			return
		}

		ctx, cancel := context.WithTimeout(context.Background(), 3*time.Second)
		defer cancel()

		url := strings.TrimRight(endpoint, "/") + telemetryPath
		req, err := http.NewRequestWithContext(ctx, http.MethodPost, url, bytes.NewReader(body))
		if err != nil {
			return
		}
		req.Header.Set("Content-Type", "application/json")

		resp, err := http.DefaultClient.Do(req)
		if err != nil {
			return // silently ignore
		}
		resp.Body.Close()
	}()

	return true
}
