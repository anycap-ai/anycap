function WorkflowList({ steps }: { steps: readonly WorkflowStep[] }) {
  return (
    <div className="mt-8 grid gap-6">
      {steps.map((step) => {
        const hasMedia = Boolean(step.image || step.video);
        const hasBoth = Boolean(step.image && step.video);
        const TextBlock = (
          <div className="flex flex-col">
            <p className="text-[11px] tracking-[0.5px] text-[#6b7d3a]" style={mono}>
              Step {step.step}
            </p>
            <h3 className="mt-3 text-[18px] leading-7 text-[#1c1f17]" style={mono}>
              {step.title}
            </h3>
            <p className="mt-3 text-sm leading-6 text-[#4d5145] md:text-[15px]">{step.body}</p>
            {step.command ? (
              <div className="mt-4">
                {step.commandLabel ? (
                  <p className="mb-2 text-[11px] tracking-[0.5px] text-[#5a5e52]" style={mono}>
                    {step.commandLabel}
                  </p>
                ) : null}
                <CommandBlock command={step.command} />
              </div>
            ) : null}
          </div>
        );

        const ImageFigure = step.image ? (
          <figure className="overflow-hidden rounded-[16px] border border-[#d4dbb8] bg-[#1c1f17]">
            <Image
              src={step.image.src}
              alt={step.image.alt}
              width={step.image.width}
              height={step.image.height}
              className="h-auto w-full"
              sizes="(min-width: 1024px) 480px, (min-width: 768px) 50vw, 100vw"
            />
            <figcaption
              className="px-4 py-3 text-[11px] leading-5 tracking-[0.4px] text-[#d4dbb8]"
              style={mono}
            >
              {step.image.caption}
            </figcaption>
          </figure>
        ) : null;

        const VideoFigure = step.video ? (
          <figure className="overflow-hidden rounded-[16px] border border-[#d4dbb8] bg-[#1c1f17]">
            <video
              src={step.video.src}
              poster={step.video.poster}
              width={step.video.width}
              height={step.video.height}
              autoPlay
              muted
              loop
              playsInline
              preload="metadata"
              aria-label={step.video.alt}
              className="h-auto w-full"
            />
            <figcaption
              className="px-4 py-3 text-[11px] leading-5 tracking-[0.4px] text-[#d4dbb8]"
              style={mono}
            >
              {step.video.caption}
            </figcaption>
          </figure>
        ) : null;

        if (hasBoth) {
          return (
            <div
              key={step.title}
              className="rounded-[24px] border border-[#d4dbb8] bg-[#fffffc]/70 p-6 md:p-7"
            >
              <div className="grid gap-6 md:grid-cols-2 md:gap-6">
                {ImageFigure}
                {VideoFigure}
              </div>
              <div className="mt-6">{TextBlock}</div>
            </div>
          );
        }

        const SingleMedia = VideoFigure ?? ImageFigure;

        return (
          <div
            key={step.title}
            className="rounded-[24px] border border-[#d4dbb8] bg-[#fffffc]/70 p-6 md:p-7"
          >
            {hasMedia && SingleMedia ? (
              <div className="grid gap-6 md:grid-cols-[minmax(0,1fr)_minmax(0,1fr)] md:items-center md:gap-8">
                {SingleMedia}
                {TextBlock}
              </div>
            ) : (
              TextBlock
            )}
          </div>
        );
      })}
    </div>
  );
}

